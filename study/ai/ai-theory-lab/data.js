  // ---------- 問題の形を確かめる(形がおかしい問題は出題しない)。問題点の配列を返す ----------
  function checkQuestion(qn) {
    var errs = [];
    if (!qn || typeof qn !== "object") return ["問題がオブジェクトではない"];
    if (typeof qn.id !== "string" || !qn.id) errs.push("id がない");
    if (typeof qn.text !== "string" || !qn.text) errs.push("text がない");
    if (qn.material !== undefined && typeof qn.material !== "string") errs.push("material が文字列ではない");
    if (!Array.isArray(qn.choices) || qn.choices.length !== 4) {
      errs.push("choices が4つではない");
    } else {
      var seen = {};
      qn.choices.forEach(function (c, i) {
        if (typeof c !== "string" || !c) { errs.push("choices[" + i + "] が空"); return; }
        var k = text(c);
        if (!k) { errs.push("choices[" + i + "] に文字がない"); return; }
        if (seen[k]) errs.push("choices に同じものがある: " + k);
        seen[k] = true;
      });
    }
    var ex = qn.explain;
    if (!(Array.isArray(ex) && ex.length > 0 && ex.every(function (l) { return typeof l === "string" && l; }))) errs.push("explain がない");
    return errs;
  }
  var validCache = {};
  function questionsOf(unitId) {
    if (validCache.hasOwnProperty(unitId)) return validCache[unitId];
    var seen = {};
    var list = (QUESTIONS[unitId] || []).filter(function (qn) {
      if (checkQuestion(qn).length > 0 || seen[qn.id]) return false;
      seen[qn.id] = true;
      return true;
    });
    validCache[unitId] = list;
    return list;
  }
  function isReady(id) { return !!unit(id) && questionsOf(id).length > 0; }

  // 出題用に1問を用意する。選択肢の並びをまぜ、answer に正解の位置を入れる
  function prepare(unitId, qn) {
    var order = shuffle([0, 1, 2, 3]);
    return {
      unitId: unitId,
      id: qn.id,
      text: qn.text,
      material: qn.material || "",
      choices: order.map(function (i) { return qn.choices[i]; }),
      answer: order.indexOf(0),
      explain: qn.explain.slice(),
      choiceLayout: qn.choiceLayout === "grid" ? "grid" : "",
      lab: unit(unitId).lab || ""
    };
  }

  // クイズ1回分。選んだ単元にできるだけ均等に割り振り、順番をまぜる。
  // 単元の問題が足りないときは、同じ問題をもう1周して補う(1周目に出たのが早い問題から)
  function buildQuiz(unitIds, count) {
    var ids = shuffle(unitIds.filter(isReady));
    if (ids.length === 0 || count <= 0) return [];
    var base = Math.floor(count / ids.length), extra = count % ids.length;
    var all = [];
    ids.forEach(function (id, i) {
      var want = base + (i < extra ? 1 : 0), pool = questionsOf(id), picked = [];
      while (picked.length < want) {
        var lap = shuffle(pool);
        for (var k = 0; k < lap.length && picked.length < want; k++) picked.push(lap[k]);
      }
      picked.forEach(function (qn) { all.push(prepare(id, qn)); });
    });
    var seq = shuffle(all);
    // 同じ問題が続けて出ないように、となりどうしが同じならずらす
    for (var i = 1; i < seq.length; i++) {
      if (seq[i].unitId === seq[i - 1].unitId && seq[i].id === seq[i - 1].id) {
        for (var j = i + 1; j < seq.length; j++) {
          if (!(seq[j].unitId === seq[i - 1].unitId && seq[j].id === seq[i - 1].id)) { var t = seq[i]; seq[i] = seq[j]; seq[j] = t; break; }
        }
      }
    }
    return seq;
  }

