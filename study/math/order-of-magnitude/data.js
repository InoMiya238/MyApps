// 上付き数字を含む "10ⁿ" 表記を作る
function formatExp(exp) {
  const map = { "-": "⁻", "0": "⁰", "1": "¹", "2": "²", "3": "³", "4": "⁴", "5": "⁵", "6": "⁶", "7": "⁷", "8": "⁸", "9": "⁹" };
  const str = String(exp).split("").map((c) => map[c] ?? c).join("");
  return "10" + str;
}
