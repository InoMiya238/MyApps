  // ---------- 図(SVG)。形式は data.js の「■ 図(SVG)」を参照 ----------
  var svg = JHSO.svg, txt = JHSO.txt, key = JHSO.key, arrow = JHSO.arrow, curve = JHSO.curve, labels = JHSO.labels;
  function n1(v) { return String(Math.round(v * 10) / 10); }
  function hasMark(opts) { return !!(opts.keys || opts.mark); }
  // 名前か記号。opts.mark が k のとき(または keys のとき)は記号を出す
  function nameOrKey(opts, k, x, y, name, o) {
    if (opts.keys || opts.mark === k) return key(x, y - 4, k, { on: !!opts.keys && opts.mark === k });
    return txt(x, y, name, o);
  }

  // 1-1 緯度の図。地球を赤道の真横から見ると、緯線はまっすぐな横線になる
  // opts: {} 名前つき / { mark: "A" } 赤道に記号 / { mark: "B" } 北極に記号(ほかの名前は出さない)
  function figLatitude(opts) {
    opts = opts || {};
    var cx = 124, cy = 104, R = 80, s = "";
    s += '<circle class="fig-shape fig-fill-0" cx="' + cx + '" cy="' + cy + '" r="' + R + '"/>';
    [30, 60].forEach(function (lat) {
      [1, -1].forEach(function (sg) {
        var y = cy - sg * R * Math.sin(lat * Math.PI / 180), hw = R * Math.cos(lat * Math.PI / 180);
        s += '<line class="fig-thin" x1="' + n1(cx - hw) + '" y1="' + n1(y) + '" x2="' + n1(cx + hw) + '" y2="' + n1(y) + '"/>';
        s += txt(cx - R - 6, y + 4, lat + "度", { cls: "fig-small", anchor: "end" });
      });
    });
    s += '<line class="fig-line" x1="' + (cx - R) + '" y1="' + cy + '" x2="' + (cx + R) + '" y2="' + cy + '"/>';
    s += txt(cx - R - 6, cy + 4, "0度", { cls: "fig-small", anchor: "end" });
    // 北緯・南緯の向き
    s += arrow(cx, cy - 4, cx, cy - R + 8, "fig-thin");
    s += arrow(cx, cy + 4, cx, cy + R - 8, "fig-thin");
    s += txt(cx + 6, cy - 22, "北緯", { cls: "fig-small", halo: true });
    s += txt(cx + 6, cy + 32, "南緯", { cls: "fig-small", halo: true });
    s += '<circle class="fig-solid" cx="' + cx + '" cy="' + (cy - R) + '" r="3"/><circle class="fig-solid" cx="' + cx + '" cy="' + (cy + R) + '" r="3"/>';
    if (hasMark(opts)) {
      if (opts.mark === "A") s += key(cx + R + 16, cy, "A");
      if (opts.mark === "B") s += key(cx + 18, cy - R - 2, "B");
    } else {
      s += labels([
        { name: "北極(北緯90度)", from: [cx, cy - R], to: [204, 20] },
        { name: "赤道(緯度0度)", to: [cx + R + 2, cy] },
        { name: "南極(南緯90度)", from: [cx, cy + R], to: [204, 190] }
      ]);
    }
    return svg(320, 206, hasMark(opts) ? "地球を横から見た図。緯線と記号がかかれている" : "緯度の図。赤道が0度で、北極が北緯90度、南極が南緯90度", s);
  }

  // 1-1 経度の図。北極の真上から見た地球。東は反時計回りの向きになる
  // opts: {} 名前つき / { mark: "C" } 東経90度の経線に記号
  function figLongitude(opts) {
    opts = opts || {};
    var cx = 160, cy = 112, R = 80, s = "";
    function pt(deg, r) { var a = deg * Math.PI / 180; return [cx + r * Math.sin(a), cy + r * Math.cos(a)]; }
    s += '<circle class="fig-shape fig-fill-0" cx="' + cx + '" cy="' + cy + '" r="' + R + '"/>';
    // 経線は、北極の名前を書くすき間をあけて、中心から少し離してかく
    for (var d = 30; d < 360; d += 30) {
      if (d === 180) continue;
      var p0 = pt(d, 20), p = pt(d, R);
      s += '<line class="fig-thin" x1="' + n1(p0[0]) + '" y1="' + n1(p0[1]) + '" x2="' + n1(p[0]) + '" y2="' + n1(p[1]) + '"/>';
    }
    s += '<line class="fig-line-2" x1="' + cx + '" y1="' + (cy - 20) + '" x2="' + cx + '" y2="' + (cy - R) + '"/>';
    s += '<line class="fig-line" x1="' + cx + '" y1="' + (cy + 20) + '" x2="' + cx + '" y2="' + (cy + R) + '"/>';
    s += '<circle class="fig-solid" cx="' + cx + '" cy="' + cy + '" r="3"/>';
    s += txt(cx, cy + 15, "北極", { cls: "fig-small", anchor: "middle" });
    // ロンドン(北緯約51度)。中心からの距離は、北極からの緯度の差に比例させる
    var ld = pt(0, R * (90 - 51.5) / 90);
    s += '<circle class="fig-point" cx="' + n1(ld[0]) + '" cy="' + n1(ld[1]) + '" r="3.5"/>';
    s += txt(ld[0] + 7, ld[1] + 4, "ロンドン", { cls: "fig-small", halo: true });
    // 東経・西経の向き(0度から180度まで)
    var e0 = pt(28, R + 12), e1 = pt(152, R + 12), w0 = pt(-28, R + 12), w1 = pt(-152, R + 12);
    s += curve("M" + n1(e0[0]) + " " + n1(e0[1]) + "A" + (R + 12) + " " + (R + 12) + " 0 0 0 " + n1(e1[0]) + " " + n1(e1[1]), "fig-shape");
    s += curve("M" + n1(w0[0]) + " " + n1(w0[1]) + "A" + (R + 12) + " " + (R + 12) + " 0 0 1 " + n1(w1[0]) + " " + n1(w1[1]), "fig-shape");
    s += txt(cx + R + 18, cy + 5, "東経", { cls: "fig-title" });
    s += txt(cx - R - 18, cy + 5, "西経", { cls: "fig-title", anchor: "end" });
    if (opts.mark === "C") {
      s += key(cx + 50, cy, "C");
    } else {
      s += txt(cx + 52, cy - 5, "東経90度", { cls: "fig-small", anchor: "middle", halo: true });
      s += txt(cx - 52, cy - 5, "西経90度", { cls: "fig-small", anchor: "middle", halo: true });
    }
    s += txt(cx, cy - R - 10, "180度の経線", { cls: "fig-small", anchor: "middle" });
    s += txt(cx, cy + R + 18, "経度0度(本初子午線)", { anchor: "middle" });
    return svg(320, 220, opts.mark ? "北極の真上から見た地球の図。経線と記号がかかれている" :
      "経度の図。北極の真上から見ると、本初子午線から反時計回りに東経、時計回りに西経が180度まで", s);
  }

  // 1-2 時差の図。経度0度から東経180度まで。15度で1時間
  // opts: { mark: "A" } 東経90度に記号をつけ、ロンドン以外の時刻をかくす
  function figTimeZone(opts) {
    opts = opts || {};
    var x0 = 70, x1 = 290, y = 64, s = "";
    function X(deg) { return x0 + (x1 - x0) * deg / 180; }
    s += txt(6, 84, "経度", { cls: "fig-small" });
    s += txt(6, 108, "時刻", { cls: "fig-small" });
    s += '<line class="fig-dash" x1="' + n1(X(180)) + '" y1="32" x2="' + n1(X(180)) + '" y2="' + y + '"/>';
    s += txt(X(180) + 10, 26, "日付変更線", { cls: "fig-small", anchor: "end" });
    s += '<line class="fig-axis" x1="' + x0 + '" y1="' + y + '" x2="' + x1 + '" y2="' + y + '"/>';
    for (var d = 0; d <= 180; d += 15) {
      var big = d % 45 === 0;
      s += '<line class="fig-axis" x1="' + n1(X(d)) + '" y1="' + (y - (big ? 6 : 4)) + '" x2="' + n1(X(d)) + '" y2="' + (y + (big ? 6 : 4)) + '"/>';
      if (big) {
        s += txt(X(d), 84, d + "度", { cls: "fig-small", anchor: "middle" });
        if (d === 0 || !opts.mark) s += txt(X(d), 108, (d / 15) + "時", { cls: "fig-label", anchor: "middle" });
      }
    }
    s += '<circle class="fig-point" cx="' + n1(X(0)) + '" cy="' + y + '" r="4"/><circle class="fig-point" cx="' + n1(X(135)) + '" cy="' + y + '" r="4"/>';
    s += txt(X(0), 46, "ロンドン", { anchor: "middle" });
    s += txt(X(135), 46, "日本(明石)", { anchor: "middle" });
    if (opts.mark === "A") {
      s += '<circle class="fig-point" cx="' + n1(X(90)) + '" cy="' + y + '" r="4"/>' + key(X(90), 42, "A");
    } else {
      s += JHSO.arrow(X(0) + 2, 124, X(135) - 2, 124, "fig-thin", { both: true });
      s += txt(X(67.5), 142, "135度 ÷ 15 = 9時間の差", { cls: "fig-small", anchor: "middle" });
    }
    s += txt(8, 168, "← 西(時刻が遅れる)", { cls: "fig-small" });
    s += txt(312, 168, "東(時刻が進む) →", { cls: "fig-small", anchor: "end" });
    return svg(320, 176, opts.mark ? "経度と時刻の関係の図。ロンドンが0時。東経90度の地点に記号がある" :
      "経度と時刻の関係の図。経度15度で1時間。ロンドンが0時のとき、東経135度の日本は9時", s);
  }

  // 1-2 国の領域の模式断面図(距離の比は正確ではない)
