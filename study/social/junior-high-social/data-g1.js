  // 1-3 雨温図(典型的な形を示す模式図。数値は目安で、北半球を想定)
  var CLIMATE = {
    tropical: { name: "熱帯", t: [26, 27, 27, 28, 28, 27, 27, 27, 27, 27, 26, 26], p: [240, 170, 190, 180, 170, 160, 160, 170, 170, 190, 250, 260] },
    dry: { name: "乾燥帯", t: [14, 15, 18, 22, 25, 28, 28, 28, 26, 24, 19, 15], p: [5, 4, 3, 1, 0, 0, 0, 0, 0, 1, 3, 5] },
    temperate: { name: "温帯", t: [3, 4, 8, 13, 18, 21, 25, 26, 22, 16, 10, 5], p: [50, 60, 120, 130, 140, 170, 150, 150, 210, 200, 90, 50] },
    cold: { name: "冷帯(亜寒帯)", t: [-18, -15, -6, 3, 10, 16, 18, 16, 9, 1, -9, -16], p: [15, 10, 15, 20, 40, 70, 90, 80, 50, 25, 20, 20] },
    polar: { name: "寒帯", t: [-26, -27, -25, -17, -6, 1, 5, 4, -1, -9, -18, -23], p: [5, 5, 5, 5, 5, 10, 25, 25, 15, 10, 6, 5] }
  };
  // opts: { noTitle: true } 気候帯の名前を出さない(問題用)
  function figClimate(kind, opts) {
    opts = opts || {};
    var c = CLIMATE[kind], L = 30, Rt = 172, T = 36, B = 132, s = "";
    function Yt(v) { return B - (v + 30) / 60 * (B - T); }
    function Yp(v) { return B - v / 300 * (B - T); }
    function Xm(i) { return L + (i + 0.5) * (Rt - L) / 12; }
    for (var v = -30; v <= 30; v += 10) {
      s += '<line class="' + (v === 0 ? "fig-thin" : "fig-grid") + '" x1="' + L + '" y1="' + n1(Yt(v)) + '" x2="' + Rt + '" y2="' + n1(Yt(v)) + '"/>';
      s += txt(L - 4, Yt(v) + 4, String(v), { cls: "fig-num", anchor: "end" });
    }
    for (var pv = 0; pv <= 300; pv += 100) s += txt(Rt + 4, Yp(pv) + 4, String(pv), { cls: "fig-num" });
    c.p.forEach(function (p, i) {
      if (p <= 0) return;
      s += '<rect class="fig-bar" x="' + n1(Xm(i) - 4) + '" y="' + n1(Yp(p)) + '" width="8" height="' + n1(B - Yp(p)) + '"/>';
    });
    s += '<path class="fig-axis" d="M' + L + " " + T + "V" + B + "H" + Rt + "V" + T + '"/>';
    s += '<path class="fig-line" d="' + c.t.map(function (t, i) { return (i ? "L" : "M") + n1(Xm(i)) + " " + n1(Yt(t)); }).join("") + '"/>';
    c.t.forEach(function (t, i) { s += '<circle class="fig-point" cx="' + n1(Xm(i)) + '" cy="' + n1(Yt(t)) + '" r="2.4"/>'; });
    [0, 2, 4, 6, 8, 10].forEach(function (i) { s += txt(Xm(i), 147, String(i + 1), { cls: "fig-num", anchor: "middle" }); });
    s += txt(Rt + 16, 147, "月", { cls: "fig-small" });
    s += txt(L - 4, 28, "気温(℃)", { cls: "fig-small" });
    s += txt(Rt + 6, 28, "降水量(mm)", { cls: "fig-small", anchor: "end" });
    if (!opts.noTitle) s += txt(102, 14, c.name, { cls: "fig-title", anchor: "middle" });
    return svg(204, 152, opts.noTitle ? "ある都市の雨温図。折れ線が気温、棒が降水量" : c.name + "の雨温図(模式図)。折れ線が気温、棒が降水量", s, { small: true });
  }

