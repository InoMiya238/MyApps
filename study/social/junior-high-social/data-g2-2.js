  // 年表の帯(縦)。上が古く、下が新しい。点の位置は年数に比例する。
  // 文字が重ならないように、できごとの名前は引き出し線で少しずらして置く。
  // o: { title, from, to, step, h, events: [{ year, name, key }] }
  // opts: { mark: "A" } A のできごとの名前だけを記号にする / { keys: true } key のあるできごとをすべて記号にする
  function figBand(o, opts) {
    opts = opts || {};
    var ax = 72, top = 24, bot = o.h - 24, gap = 21, s = "";
    function Y(yr) { return top + (bot - top) * (yr - o.from) / (o.to - o.from); }
    s += arrow(ax, top - 12, ax, bot + 16, "fig-axis");
    for (var t = o.from; t <= o.to; t += o.step) {
      s += '<line class="fig-axis" x1="' + (ax - 5) + '" y1="' + n1(Y(t)) + '" x2="' + ax + '" y2="' + n1(Y(t)) + '"/>';
      s += txt(ax - 9, Y(t) + 4, String(t), { cls: "fig-num", anchor: "end" });
    }
    var ev = o.events, ls = ev.map(function (e) { return Y(e.year); });
    for (var i = 1; i < ls.length; i++) ls[i] = Math.max(ls[i], ls[i - 1] + gap);
    ls[ls.length - 1] = Math.min(ls[ls.length - 1], o.h - 14);
    for (var j = ls.length - 2; j >= 0; j--) ls[j] = Math.min(ls[j], ls[j + 1] - gap);
    ev.forEach(function (e, k) {
      var y = Y(e.year), l = ls[k];
      s += '<line class="fig-thin" x1="' + (ax + 5) + '" y1="' + n1(y) + '" x2="' + (ax + 30) + '" y2="' + n1(l) + '"/>';
      s += '<circle class="fig-point" cx="' + ax + '" cy="' + n1(y) + '" r="4"/>';
      s += txt(ax + 34, l + 4.5, e.year + "年", { cls: "fig-small" });
      var asKey = !!e.key && (!!opts.keys || opts.mark === e.key);
      if (asKey) s += key(ax + 98, l, e.key, { on: !!opts.keys && opts.mark === e.key });
      else s += txt(ax + 84, l + 4.5, e.name);
    });
    var label = opts.keys || opts.mark ? o.title + "の年表。上が古く下が新しい。一部のできごとが記号になっている" :
      o.title + "の年表。" + ev.map(function (e) { return e.year + "年 " + e.name; }).join("、");
    return svg(320, o.h, label, s);
  }

